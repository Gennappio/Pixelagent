export type IconName = keyof typeof ICONS;

/** A horizontal stretch of drawn pixels: `width` of them starting at column `x` of row `y`. */
export interface Run {
  x: number;
  y: number;
  width: number;
}

/** The size of a bitmap, in its own pixels. Every row is as wide as the first. */
export function sizeOf(bitmap: readonly string[]): { width: number; height: number } {
  return { width: bitmap[0]?.length ?? 0, height: bitmap.length };
}

/** A bitmap as the fewest rectangles one pixel high: what there is to draw, whatever draws it. */
export function runs(bitmap: readonly string[]): Run[] {
  const found: Run[] = [];
  bitmap.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x++) {
      const drawn = row[x] === "#";
      if (drawn && start < 0) start = x;
      if (!drawn && start >= 0) {
        found.push({ x: start, y, width: x - start });
        start = -1;
      }
    }
  });
  return found;
}

/** The icon of a tool: its own if it has one, else the one any tool gets. */
export function toolIcon(tool: string): IconName {
  return tool in ICONS && (tool === "web_search" || tool === "send_email" || tool === "calculator") ? (tool as IconName) : "tool";
}
